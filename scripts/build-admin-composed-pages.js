/* Mechanical extraction of existing, trusted local views into Admin-only modules.
 * Run with node scripts/build-admin-composed-pages.js after editing source views.
 * The original role pages are never rewritten by this build. */
"use strict";
const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "..");
const views = {
  dashboard: { page: "Dashboard_Admin.html", css: ["agent-dashboard.css", "admin-dashboard.css"], scripts: [] },
  "help-support": { page: "help-support.html", css: ["help-support.css"], scripts: [] },
  "strategy-manager": { page: "strategy-master.html", css: ["strategy-master.css"], scripts: ["strategy-master-template-source.js", "strategy-master.js"] },
};
const output = ['/* Generated by build-admin-composed-pages.js; do not edit. */', 'window.IneburaAdminComposed = {};'];
for (const [id, config] of Object.entries(views)) {
  const source = fs.readFileSync(path.join(root, "pages", config.page), "utf8");
  let body = source.match(/<body\b[^>]*>([\s\S]*?)<\/body>/i)[1];
  const inline = [...body.matchAll(/<script\b(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)].map(m => m[1]);
  body = body.replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, "").replace(/<div\b[^>]*data-(?:shared-header|admin-shell)[^>]*><\/div>/g, "");
  const scripts = [...config.scripts.map(file => fs.readFileSync(path.join(root, "scripts", file), "utf8")), ...inline];
  let code = scripts.join("\n").replace(/\bwindow\.localStorage\b|(?<![\w.])localStorage\b/g, "window.IneburaAdminPreviewStorage");
  code = code.replace(/document\.addEventListener\("DOMContentLoaded",/g, "window.IneburaAdminReady(");
  if (id === "dashboard") {
    // Avoid a completion callback recursively updating its own chart.
    code = code.replace('charts.systemHealth.$needleVisible = true; charts.systemHealth.update("none");', 'charts.systemHealth.$needleVisible = true;');
    code = code.replace('    initCardMotion();', '    // Static reference state; no counter animation.');
  }
  output.push(`window.IneburaAdminComposed[${JSON.stringify(id)}] = {html:${JSON.stringify(body)}, css:${JSON.stringify(config.css)}, start(){\n${code}\n}};`);
}
fs.writeFileSync(path.join(root, "scripts", "admin-composed-generated.js"), output.join("\n"));
console.log("Built 3 Admin-only composed views; original pages unchanged.");
