/* Run with: node scripts/validate-invoice-master.js */
"use strict";
const assert = require("node:assert/strict");
const core = require("./invoice-master-core.js");
const XLSX = require("./vendor/xlsx.full.min.js");
const seed = { company: "Company A", fields: Object.fromEntries(core.headers.map((h) => [h, ""])) };
Object.assign(seed.fields, { "Customer Code": "000123", "Customer Name": "Test Customer", "Invoice No": "INV-001", "Invoice Date": "2026-09-05", "Invoice Due Date": "2026-09-20", "Invoice Value": 125000, "Total Outstanding": 125000, Currency: "INR" });
Object.assign(seed, { broadStatus: "Work In Progress", primaryStatus: "Part Collected", subStatus: "Part Payment Made" });
const update = (header, value) => core.preview([["Invoice No", header], ["INV-001", value]], [seed], "Company A", "update");
const change = update("Invoice Due Date", "07/10/2026");
assert.equal(change[0].next.fields["Invoice Due Date"], "2026-10-07");
assert.equal(core.apply(change, [seed])[0].broadStatus, seed.broadStatus);
assert.equal(seed.fields["Invoice Due Date"], "2026-09-20", "Preview must not mutate stored invoices");
assert.equal(update("Total Outstanding", "0")[0].next.fields["Total Outstanding"], 0);
assert.equal(update("Customer Name", "")[0].next.fields["Customer Name"], seed.fields["Customer Name"]);
assert.equal(update("Customer Name", "")[0].kind, "unchanged");
assert.equal(update("Invoice Value", "1,35,000")[0].next.fields["Invoice Value"], 135000);
assert.equal(update("Customer Code", "000007")[0].next.fields["Customer Code"], "000007");
for (const header of ["Broad Status", "Primary Status", "Substatus", "Sub Status", "Invoice Status"]) {
  const result = update(header, "Changed");
  assert.match(result[0].errors.join(), /view only/);
  assert.deepEqual(core.apply(result, [seed]), [seed]);
}
const duplicates = core.preview([["Invoice No", "City"], ["INV-001", "Mumbai"], ["INV-001", "Delhi"]], [seed], "Company A", "update");
assert.ok(duplicates.every((p) => p.errors.some((e) => e.includes("Duplicate"))));
assert.match(core.preview([["Invoice No", "City"], ["INV-001", "Mumbai"]], [seed], "Company B", "update")[0].errors.join(), /not found/);
assert.match(core.preview([core.headers, core.headers.map((h) => seed.fields[h])], [seed], "Company A", "add")[0].errors.join(), /already exists/);
const newInvoice = core.clone(seed); newInvoice.fields["Invoice No"] = "INV-NEW";
const add = core.preview([core.headers, core.headers.map((h) => newInvoice.fields[h])], [seed], "Company A", "add");
assert.equal(add[0].kind, "add");
assert.equal(core.apply(add, [seed]).length, 2);
assert.match(update("Invoice Due Date", "2026-09-01")[0].errors.join(), /before Invoice Date/);
assert.throws(() => core.convert("Invoice Date", "2026-02-30"), /Invalid date/);
assert.match(update("Invoice Value", "-20")[0].errors.join(), /non-negative/);
assert.throws(() => core.preview([["Invoice No", "City", "City"]], [], "Company A", "add"), /Duplicate column/);
assert.throws(() => core.preview([["Invoice No", "Unexpected"]], [], "Company A", "add"), /Unknown columns/);
assert.throws(() => core.preview([core.headers], [], "Company A", "add"), /no invoice rows/);
assert.deepEqual(core.parseCSV('\uFEFFInvoice No,Description\r\nINV-001,"First, line\nSecond ""quoted"" line"\r\n'), [["Invoice No", "Description"], ["INV-001", 'First, line\nSecond "quoted" line']]);
assert.throws(() => core.parseCSV('Invoice No\n"unclosed'), /Unclosed/);
const modified = core.clone(seed); modified.fields.City = "Changed elsewhere";
assert.throws(() => core.apply(change, [modified]), /changed since preview/);
assert.throws(() => core.apply(add, [seed, newInvoice]), /added since preview/);
const workbook = XLSX.utils.book_new();
const excelRows = [["Invoice No", "Invoice Due Date", "PO Number"], ["INV-001", new Date("2026-10-07T00:00:00Z"), "PO-NEW"]];
XLSX.utils.book_append_sheet(workbook, XLSX.utils.aoa_to_sheet(excelRows), "Invoices");
const bytes = XLSX.write(workbook, { type: "buffer", bookType: "xlsx" });
const decoded = XLSX.read(bytes, { type: "buffer", cellDates: true });
const matrix = XLSX.utils.sheet_to_json(decoded.Sheets.Invoices, { header: 1, raw: true, defval: "" });
const excelUpdate = core.preview(matrix, [seed], "Company A", "update");
assert.equal(excelUpdate[0].next.fields["Invoice Due Date"], "2026-10-07");
assert.equal(excelUpdate[0].next.fields["PO Number"], "PO-NEW");
console.log("Invoice Master validation passed: identity, locked statuses, CSV/Excel, blanks/zero values, dates, duplicate/error rows and stale previews.");
